-- ============================================================
-- PARTNER PROFILES POLICIES
-- ============================================================

DROP POLICY IF EXISTS "Authenticated users can view partner profiles"
ON public.partner_profiles;

CREATE POLICY "Authenticated users can view partner profiles"
ON public.partner_profiles
FOR SELECT
TO authenticated
USING (true);


DROP POLICY IF EXISTS "Partners can insert own profile"
ON public.partner_profiles;

CREATE POLICY "Partners can insert own profile"
ON public.partner_profiles
FOR INSERT
TO authenticated
WITH CHECK (
    id = auth.uid()
    AND EXISTS (
        SELECT 1
        FROM public.users
        WHERE id = auth.uid()
          AND role = 'partner'
    )
);


DROP POLICY IF EXISTS "Partners can update own profile"
ON public.partner_profiles;

CREATE POLICY "Partners can update own profile"
ON public.partner_profiles
FOR UPDATE
TO authenticated
USING (id = auth.uid())
WITH CHECK (id = auth.uid());


DROP POLICY IF EXISTS "Partners can delete own profile"
ON public.partner_profiles;

CREATE POLICY "Partners can delete own profile"
ON public.partner_profiles
FOR DELETE
TO authenticated
USING (id = auth.uid());


