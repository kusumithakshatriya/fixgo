-- 1. Partner profiles
CREATE TABLE IF NOT EXISTS public.partner_profiles (
    id uuid PRIMARY KEY
        REFERENCES public.users(id) ON DELETE CASCADE,

    bio text,

    profile_image_path text,

    experience_years integer NOT NULL DEFAULT 0
        CHECK (experience_years >= 0),

    rating numeric(3,2) NOT NULL DEFAULT 0
        CHECK (rating >= 0 AND rating <= 5),

    total_jobs integer NOT NULL DEFAULT 0
        CHECK (total_jobs >= 0),

    is_verified boolean NOT NULL DEFAULT false,

    is_online boolean NOT NULL DEFAULT false,

    is_available boolean NOT NULL DEFAULT false,

    service_radius_km numeric(6,2) NOT NULL DEFAULT 10
        CHECK (service_radius_km > 0),

    created_at timestamptz NOT NULL DEFAULT now(),

    updated_at timestamptz NOT NULL DEFAULT now()
);


-- 2. Partner skills
CREATE TABLE IF NOT EXISTS public.partner_skills (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    partner_id uuid NOT NULL
        REFERENCES public.partner_profiles(id) ON DELETE CASCADE,

    service_id bigint NOT NULL
        REFERENCES public.services(id) ON DELETE CASCADE,

    experience_years integer NOT NULL DEFAULT 0
        CHECK (experience_years >= 0),

    created_at timestamptz NOT NULL DEFAULT now(),

    UNIQUE(partner_id, service_id)
);


-- 3. Partner service areas
CREATE TABLE IF NOT EXISTS public.partner_service_areas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    partner_id uuid NOT NULL
        REFERENCES public.partner_profiles(id) ON DELETE CASCADE,

    area_name text NOT NULL,

    latitude numeric(10,7),

    longitude numeric(10,7),

    created_at timestamptz NOT NULL DEFAULT now()
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_partner_profiles_available
ON public.partner_profiles (
