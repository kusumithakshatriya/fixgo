ON public.partner_skills(partner_id);

CREATE INDEX IF NOT EXISTS idx_partner_skills_service_id
ON public.partner_skills(service_id);

CREATE INDEX IF NOT EXISTS idx_partner_service_areas_partner_id
ON public.partner_service_areas(partner_id);


-- ============================================================
-- UPDATED_AT TRIGGER
-- ============================================================

CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS partner_profiles_updated_at
ON public.partner_profiles;

CREATE TRIGGER partner_profiles_updated_at
BEFORE UPDATE ON public.partner_profiles
FOR EACH ROW
EXECUTE FUNCTION public.handle_updated_at();


-- ============================================================
-- VERIFY USER IS A PARTNER
-- ============================================================

CREATE OR REPLACE FUNCTION public.check_user_is_partner()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM public.users
        WHERE id = auth.uid()
          AND role = 'partner'
    ) THEN
        RAISE EXCEPTION 'Only partner users can modify partner profile';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS check_partner_role
ON public.partner_profiles;

CREATE TRIGGER check_partner_role
BEFORE INSERT OR UPDATE ON public.partner_profiles
FOR EACH ROW
EXECUTE FUNCTION public.check_user_is_partner();


